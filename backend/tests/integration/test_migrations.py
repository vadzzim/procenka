"""Alembic migrations apply from scratch, roll back fully and match the models."""

import pytest
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import text
from sqlalchemy.engine import URL
from sqlalchemy.ext.asyncio import create_async_engine

from app.db.models import Base
from tests.conftest import run_alembic

pytestmark = pytest.mark.integration

EXPECTED_TABLES = {
    "products",
    "published_prices",
    "runs",
    "source_results",
    "offers",
    "calculations",
}
EXPECTED_ENUMS = {
    "run_status",
    "run_trigger",
    "source",
    "source_status",
    "source_error_kind",
    "result_state",
    "result_reason",
}


async def _schema_objects(url: URL) -> tuple[set[str], set[str]]:
    engine = create_async_engine(url)
    try:
        async with engine.connect() as conn:
            tables = set(
                (
                    await conn.scalars(
                        text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
                    )
                ).all()
            )
            enums = set(
                (
                    await conn.scalars(
                        text(
                            "SELECT t.typname FROM pg_type t "
                            "JOIN pg_namespace n ON n.oid = t.typnamespace "
                            "WHERE n.nspname = 'public' AND t.typtype = 'e'"
                        )
                    )
                ).all()
            )
    finally:
        await engine.dispose()
    return tables, enums


def test_models_cover_expected_tables() -> None:
    assert set(Base.metadata.tables) == EXPECTED_TABLES


async def test_upgrade_downgrade_upgrade_from_empty_database(scratch_database_url: URL) -> None:
    assert await _schema_objects(scratch_database_url) == (set(), set())

    await run_alembic(scratch_database_url, "upgrade", "head")
    assert await _schema_objects(scratch_database_url) == (
        EXPECTED_TABLES | {"alembic_version"},
        EXPECTED_ENUMS,
    )
    await run_alembic(scratch_database_url, "check")

    await run_alembic(scratch_database_url, "downgrade", "base")
    assert await _schema_objects(scratch_database_url) == ({"alembic_version"}, set())

    await run_alembic(scratch_database_url, "upgrade", "head")
    assert await _schema_objects(scratch_database_url) == (
        EXPECTED_TABLES | {"alembic_version"},
        EXPECTED_ENUMS,
    )
    await run_alembic(scratch_database_url, "check")


async def test_check_detects_schema_drift(scratch_database_url: URL) -> None:
    """``alembic check`` is not vacuous: a missing partial unique index is reported."""
    await run_alembic(scratch_database_url, "upgrade", "head")
    engine = create_async_engine(scratch_database_url)
    try:
        async with engine.begin() as conn:
            await conn.execute(text("DROP INDEX uq_runs_single_active"))
    finally:
        await engine.dispose()

    with pytest.raises(AutogenerateDiffsDetected, match="uq_runs_single_active"):
        await run_alembic(scratch_database_url, "check")
